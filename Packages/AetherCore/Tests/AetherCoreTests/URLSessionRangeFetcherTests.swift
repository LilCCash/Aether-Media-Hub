/// A URL protocol that plays the part of the real source. Redirects are real redirects, so the delegate and the guard are exercised.
private final class RangeStub: URLProtocol {
    struct Reply {
        var status = 206
        var headers: [String: String] = [:]
        var body = Data()
        var error: URLError?
        var redirectTo: URL?
    }

    private static let lock = NSLock()
    private static var handler: ((URLRequest) -> Reply)?
    private static var recorded: [URLRequest] = []

    static func install(_ handler: @escaping (URLRequest) -> Reply) {
        lock.lock()
        self.handler = handler
        recorded = []
        lock.unlock()
    }

    static var seen: [URLRequest] {
        lock.lock()
        defer { lock.unlock() }
        return recorded
    }

    override class func canInit(with request: URLRequest) -> Bool { return true }
    override class func canonicalRequest(for request: URLRequest) -> URLRequest { return request }

    override func startLoading() {
        RangeStub.lock.lock()
        RangeStub.recorded.append(request)
        let handler = RangeStub.handler
        RangeStub.lock.unlock()
        guard let url = request.url, let reply = handler?(request) else {
            client?.urlProtocol(self, didFailWithError: URLError(.badURL))
            return
        }
        if let error = reply.error {
            client?.urlProtocol(self, didFailWithError: error)
            return
        }
        if let target = reply.redirectTo {
            let response = HTTPURLResponse(url: url, statusCode: 302, httpVersion: "HTTP/1.1", headerFields: ["Location": target.absoluteString])!
            client?.urlProtocol(self, wasRedirectedTo: URLRequest(url: target), redirectResponse: response)
            return
        }
        let response = HTTPURLResponse(url: url, statusCode: reply.status, httpVersion: "HTTP/1.1", headerFields: reply.headers)!
        client?.urlProtocol(self, didReceive: response, cacheStoragePolicy: .notAllowed)
        if !reply.body.isEmpty { client?.urlProtocol(self, didLoad: reply.body) }
        client?.urlProtocolDidFinishLoading(self)
    }

    override func stopLoading() {}
}

final class URLSessionRangeFetcherTests: XCTestCase {
    private let resolver = StaticHostResolver([
        "cdn.example.com": [.v4(93, 184, 216, 34)],
        "other.example.net": [.v4(151, 101, 1, 69)],
        "a.example.com": [.v4(93, 184, 216, 1)],
        "b.example.com": [.v4(93, 184, 216, 2)],
        "c.example.com": [.v4(93, 184, 216, 3)],
        "d.example.com": [.v4(93, 184, 216, 4)],
        "e.example.com": [.v4(93, 184, 216, 5)]
    ])

    private func makeFetcher(_ url: String = "https://cdn.example.com/dl/f.mkv?key=SECRET", headers: [String: String] = ["Authorization": "Bearer X"],
                             limits: RelayLimits = .standard) -> URLSessionRangeFetcher {
        let configuration = URLSessionRangeFetcher.makeConfiguration()
        configuration.protocolClasses = [RangeStub.self]
        let guardian = UpstreamGuard(allowPrivateOrigin: false, selfAddresses: ["192.168.1.5"], resolver: resolver)
        return URLSessionRangeFetcher(upstream: RelayUpstream(url: URL(string: url)!, headers: headers), guardian: guardian, limits: limits,
                                      configuration: configuration)
    }

    /// 206 for a `Range: bytes=a-b` request over `total` generated bytes.
    private static func ranged(_ request: URLRequest, total: Int64 = 1000, contentType: String = "video/x-matroska") -> RangeStub.Reply {
        guard case .single(.from(let first, to: let wanted)) = RelayRangeHeader.parse(request.value(forHTTPHeaderField: "Range")), first < total else {
            return RangeStub.Reply(status: 416, headers: ["Content-Range": "bytes */\(total)", "Content-Length": "0"])
        }
        let last = min(wanted ?? (total - 1), total - 1)
        let body = MemoryRelaySource.expected(first...last)
        return RangeStub.Reply(status: 206, headers: ["Content-Range": "bytes \(first)-\(last)/\(total)", "Content-Length": String(body.count),
                                                      "Content-Type": contentType], body: body)
    }

    private func failure(_ work: () async throws -> Void) async -> RelayError? {
        do {
            try await work()
            return nil
        } catch {
            return error as? RelayError
        }
    }

    // MARK: Configuration

    func testTheSessionIsEphemeralAndRefusesOldTLS() {
        let configuration = URLSessionRangeFetcher.makeConfiguration()
        XCTAssertNil(configuration.urlCache)
        XCTAssertNil(configuration.httpCookieStorage)
        XCTAssertNil(configuration.urlCredentialStorage)
        XCTAssertFalse(configuration.httpShouldSetCookies)
        XCTAssertFalse(configuration.waitsForConnectivity)
        XCTAssertEqual(configuration.tlsMinimumSupportedProtocolVersion, .TLSv12)
    }

    func testTheDelegateNeverAnswersAuthenticationChallenges() {
        let delegate = makeFetcher().sessionDelegateForTesting
        XCTAssertFalse(delegate.responds(to: #selector(URLSessionDelegate.urlSession(_:didReceive:completionHandler:))),
                       "system trust evaluation must stay in charge")
    }

    // MARK: Probe

    func testTheProbeAsksForTheFirstByteWithTheAddonsHeaders() async throws {
        RangeStub.install { URLSessionRangeFetcherTests.ranged($0) }
        let resource = try await makeFetcher().probe()
        XCTAssertEqual(resource.length, 1000)
        XCTAssertTrue(resource.acceptsRanges)
        let request = try XCTUnwrap(RangeStub.seen.first)
        XCTAssertEqual(request.value(forHTTPHeaderField: "Range"), "bytes=0-0")
        XCTAssertEqual(request.value(forHTTPHeaderField: "Authorization"), "Bearer X")
        XCTAssertEqual(request.value(forHTTPHeaderField: "Accept-Encoding"), "identity")
        XCTAssertEqual(request.value(forHTTPHeaderField: "User-Agent"), "Aether/1.0")
    }

    func testASourceThatIgnoresRangesIsRefused() async {
        RangeStub.install { _ in RangeStub.Reply(status: 200, headers: ["Content-Type": "video/mp4", "Content-Length": "5"], body: Data(count: 5)) }
        let plain = await failure { _ = try await makeFetcher().probe() }
        XCTAssertEqual(plain, .upstreamNoRanges)

        RangeStub.install { _ in RangeStub.Reply(status: 206, headers: ["Content-Range": "bytes 0-0/*", "Content-Length": "1"], body: Data(count: 1)) }
        let unknownSize = await failure { _ = try await makeFetcher().probe() }
        XCTAssertEqual(unknownSize, .upstreamNoRanges)
    }

    func testProbeFailuresAreReducedToStatusesAndTypes() async throws {
        RangeStub.install { _ in RangeStub.Reply(status: 403) }
        let refused = await failure { _ = try await makeFetcher().probe() }
        XCTAssertEqual(refused, .upstreamRejected(status: 403))

        RangeStub.install { URLSessionRangeFetcherTests.ranged($0, contentType: "text/html; charset=utf-8") }
        let page = await failure { _ = try await makeFetcher().probe() }
        XCTAssertEqual(page, .upstreamNotMedia)

        RangeStub.install { _ in RangeStub.Reply(status: 416, headers: ["Content-Range": "bytes */0", "Content-Length": "0"]) }
        let empty = try await makeFetcher().probe()
        XCTAssertEqual(empty.length, 0)
    }

    // MARK: Windows

    func testAWindowIsFetchedExactly() async throws {
        RangeStub.install { URLSessionRangeFetcherTests.ranged($0) }
        let data = try await makeFetcher().fetch(10...19)
        XCTAssertEqual(data, MemoryRelaySource.expected(10...19))
        XCTAssertEqual(RangeStub.seen.last?.value(forHTTPHeaderField: "Range"), "bytes=10-19")
    }

    func testAWrongOrShortWindowIsABadRange() async {
        RangeStub.install { _ in
            RangeStub.Reply(status: 206, headers: ["Content-Range": "bytes 11-20/1000", "Content-Length": "10", "Content-Type": "video/mp4"], body: Data(count: 10))
        }
        let shifted = await failure { _ = try await makeFetcher().fetch(10...19) }
        XCTAssertEqual(shifted, .upstreamBadRange)

        RangeStub.install { _ in
            RangeStub.Reply(status: 206, headers: ["Content-Range": "bytes 10-19/1000", "Content-Length": "10", "Content-Type": "video/mp4"], body: Data(count: 9))
        }
        let short = await failure { _ = try await makeFetcher().fetch(10...19) }
        XCTAssertEqual(short, .upstreamBadRange)

        RangeStub.install { _ in
            RangeStub.Reply(status: 206, headers: ["Content-Range": "bytes 10-19/1000", "Content-Length": "10", "Content-Type": "video/mp4",
                                                   "Content-Encoding": "gzip"], body: Data(count: 10))
        }
        let compressed = await failure { _ = try await makeFetcher().fetch(10...19) }
        XCTAssertEqual(compressed, .upstreamBadRange)
    }

    func testARefusedWindowCarriesOnlyTheStatus() async {
        RangeStub.install { _ in RangeStub.Reply(status: 403) }
        let error = await failure { _ = try await makeFetcher().fetch(0...9) }
        XCTAssertEqual(error, .upstreamRejected(status: 403))
        RangeStub.install { _ in RangeStub.Reply(status: 410) }
        let gone = await failure { _ = try await makeFetcher().fetch(0...9) }
        XCTAssertEqual(gone, .upstreamRejected(status: 410))
    }

    func testANetworkErrorCarriesOnlyItsCode() async {
        RangeStub.install { _ in RangeStub.Reply(error: URLError(.timedOut, userInfo: [NSURLErrorFailingURLStringErrorKey: "https://cdn.example.com/f?key=SECRET"])) }
        let error = await failure { _ = try await makeFetcher().fetch(0...9) }
        XCTAssertEqual(error, .upstreamUnreachable(code: -1001))
        XCTAssertFalse("\(String(describing: error))".contains("SECRET"))
        XCTAssertFalse(String(reflecting: error).contains("cdn.example.com"))
    }

    func testAnInvalidatedFetcherRefusesNewRequests() async {
        RangeStub.install { URLSessionRangeFetcherTests.ranged($0) }
        let fetcher = makeFetcher()
        fetcher.invalidate()
        let error = await failure { _ = try await fetcher.fetch(0...9) }
        XCTAssertEqual(error, .upstreamUnreachable(code: NSURLErrorCancelled))
    }

    func testAnOriginInTheHomeNetworkIsRefusedBeforeAnyRequest() async {
        RangeStub.install { URLSessionRangeFetcherTests.ranged($0) }
        let error = await failure { _ = try await makeFetcher("https://192.168.1.20/f.mkv").fetch(0...9) }
        XCTAssertEqual(error, .blockedTarget)
        XCTAssertTrue(RangeStub.seen.isEmpty)
    }

    // MARK: Redirects

    func testARedirectToAnotherHostDropsTheHeadersAndTheKey() async throws {
        RangeStub.install { request in
            if request.url?.host == "cdn.example.com" {
                return RangeStub.Reply(redirectTo: URL(string: "https://other.example.net/file.mkv")!)
            }
            return URLSessionRangeFetcherTests.ranged(request)
        }
        let data = try await makeFetcher().fetch(0...9)
        XCTAssertEqual(data, MemoryRelaySource.expected(0...9))
        let seen = RangeStub.seen
        XCTAssertEqual(seen.count, 2)
        XCTAssertEqual(seen[0].value(forHTTPHeaderField: "Authorization"), "Bearer X")
        XCTAssertTrue(seen[0].url?.absoluteString.contains("SECRET") ?? false)
        XCTAssertNil(seen[1].value(forHTTPHeaderField: "Authorization"), "the addon's headers must not follow a redirect to another host")
        XCTAssertFalse(seen[1].url?.absoluteString.contains("SECRET") ?? true, "the key in the original address must not follow either")
        XCTAssertEqual(seen[1].value(forHTTPHeaderField: "Range"), "bytes=0-9")
        XCTAssertEqual(seen[1].value(forHTTPHeaderField: "Accept-Encoding"), "identity")
    }

    func testRedirectsToTheDeviceOrTheHomeNetworkAreRefused() async {
        for target in ["https://127.0.0.1/x", "https://192.168.1.1/x", "https://169.254.169.254/latest", "https://192.168.1.5/x", "http://other.example.net/x"] {
            RangeStub.install { request in
                request.url?.host == "cdn.example.com" ? RangeStub.Reply(redirectTo: URL(string: target)!) : URLSessionRangeFetcherTests.ranged(request)
            }
            let error = await failure { _ = try await makeFetcher().fetch(0...9) }
            XCTAssertEqual(error, .blockedTarget, target)
            XCTAssertEqual(RangeStub.seen.count, 1, "nothing may be requested from \(target)")
        }
    }

    func testTooManyRedirectsAreRefused() async {
        let chain = ["a.example.com": "b.example.com", "b.example.com": "c.example.com", "c.example.com": "d.example.com",
                     "d.example.com": "e.example.com"]
        RangeStub.install { request in
            if let host = request.url?.host, let next = chain[host] { return RangeStub.Reply(redirectTo: URL(string: "https://\(next)/f.mkv")!) }
            return URLSessionRangeFetcherTests.ranged(request)
        }
        let error = await failure { _ = try await makeFetcher("https://a.example.com/f.mkv").fetch(0...9) }
        XCTAssertEqual(error, .blockedTarget)
        XCTAssertEqual(RangeStub.seen.map { $0.url?.host ?? "" }, ["a.example.com", "b.example.com", "c.example.com", "d.example.com"])

        // Three redirects are fine.
        RangeStub.install { request in
            if let host = request.url?.host, host != "d.example.com", let next = chain[host] { return RangeStub.Reply(redirectTo: URL(string: "https://\(next)/f.mkv")!) }
            return URLSessionRangeFetcherTests.ranged(request)
        }
        let ok = await failure { _ = try await makeFetcher("https://a.example.com/f.mkv").fetch(0...9) }
        XCTAssertNil(ok)
    }

    // MARK: The gate

    func testNoMoreThanThePermittedRequestsRunAtOnce() async throws {
        final class Peak: @unchecked Sendable {
            private let lock = NSLock()
            private var current = 0
            private(set) var peak = 0
            func enter() { lock.lock(); current += 1; peak = max(peak, current); lock.unlock() }
            func leave() { lock.lock(); current -= 1; lock.unlock() }
            var maximum: Int { lock.lock(); defer { lock.unlock() }; return peak }
        }
        let gate = AsyncGate(permits: 2)
        let tracker = Peak()
        try await withThrowingTaskGroup(of: Void.self) { group in
            for _ in 0..<8 {
                group.addTask {
                    try await gate.acquire()
                    tracker.enter()
                    _ = try? await Task.sleep(nanoseconds: 10_000_000)
                    tracker.leave()
                    gate.release()
                }
            }
            try await group.waitForAll()
        }
        XCTAssertLessThanOrEqual(tracker.maximum, 2)
        XCTAssertGreaterThanOrEqual(tracker.maximum, 1)
    }

    // MARK: The whole chain

    func testTheSecretNeverReachesTheReceiver() async throws {
        let secret = "SECRET-H"
        RangeStub.install { request in
            guard request.value(forHTTPHeaderField: "Authorization") == secret else { return RangeStub.Reply(status: 403) }
            return URLSessionRangeFetcherTests.ranged(request)
        }
        var limits = RelayLimits()
        limits.windowSize = 300
        let fetcher = makeFetcher("https://cdn.example.com/f.mkv", headers: ["Authorization": secret], limits: limits)
        let source = HTTPRangeSource(leaf: "video.mkv", contentType: "video/x-matroska", fetcher: fetcher, limits: limits)
        try await source.prepare()

        let registry = RelaySessionRegistry(limits: limits)
        let log = RelayLogBox()
        let server = RelayServer(registry: registry, configuration: RelayServer.Configuration(bindAddress: "127.0.0.1", allowLoopbackPeers: true, limits: limits),
                                 log: { log.add($0) })
        let port = try await server.start()
        addTeardownBlock { server.stop() }
        let created = try registry.create(source: source, leaf: "video.mkv", owner: .cast(.googleCast), peerRule: .any)

        func exchange(_ headers: [String]) async -> (raw: Data, reply: RelayTestReply?) {
            let client = RelayRawClient(port: port)
            guard await client.connect() else { return (Data(), nil) }
            var text = "GET /r/\(created.token)/video.mkv HTTP/1.1\r\nHost: 127.0.0.1\r\n"
            for header in headers { text += header + "\r\n" }
            client.send(Data((text + "\r\n").utf8))
            _ = await relayPollUntil(8) { client.finished }
            client.close()
            return (client.data, RelayTestReply.parse(client.data))
        }

        let whole = await exchange([])
        XCTAssertEqual(whole.reply?.status, 200)
        XCTAssertTrue(whole.reply?.body == MemoryRelaySource.expected(0...999))
        XCTAssertFalse(String(decoding: whole.raw, as: UTF8.self).contains(secret))

        let part = await exchange(["Range: bytes=100-799"])
        XCTAssertEqual(part.reply?.status, 206)
        XCTAssertEqual(part.reply?.headers["content-range"], "bytes 100-799/1000")
        XCTAssertTrue(part.reply?.body == MemoryRelaySource.expected(100...799))

        let upstream = RangeStub.seen
        XCTAssertFalse(upstream.isEmpty)
        XCTAssertTrue(upstream.allSatisfy { $0.value(forHTTPHeaderField: "Authorization") == secret }, "the real source must have been asked with the header")
        for message in log.messages { XCTAssertFalse(message.contains(secret), message) }
    }

    func testAnHtmlPageFromTheSourceIsABadGatewayForTheReceiver() async throws {
        RangeStub.install { request in
            if request.value(forHTTPHeaderField: "Range") == "bytes=0-0" { return URLSessionRangeFetcherTests.ranged(request) }
            return URLSessionRangeFetcherTests.ranged(request, contentType: "text/html")
        }
        var limits = RelayLimits()
        limits.windowSize = 300
        let source = HTTPRangeSource(leaf: "video.mkv", contentType: "video/x-matroska", fetcher: makeFetcher(limits: limits), limits: limits)
        try await source.prepare()
        let registry = RelaySessionRegistry(limits: limits)
        let server = RelayServer(registry: registry, configuration: RelayServer.Configuration(bindAddress: "127.0.0.1", allowLoopbackPeers: true, limits: limits),
                                 log: { _ in })
        let port = try await server.start()
        addTeardownBlock { server.stop() }
        let created = try registry.create(source: source, leaf: "video.mkv", owner: .cast(.googleCast), peerRule: .any)
        let client = RelayRawClient(port: port)
        guard await client.connect() else { return XCTFail("could not connect") }
        client.send(Data("GET /r/\(created.token)/video.mkv HTTP/1.1\r\nHost: x\r\n\r\n".utf8))
        _ = await relayPollUntil(8) { client.finished }
        client.close()
        XCTAssertEqual(RelayTestReply.parse(client.data)?.status, 502)
    }
